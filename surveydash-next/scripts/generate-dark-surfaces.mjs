import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
// PostCSS is already part of the installed Tailwind toolchain. This script only generates CSS.
const require = createRequire(import.meta.url);
const postcss = createRequire(require.resolve('@tailwindcss/postcss'))('postcss');
export function darkColor(property, value) {
  if (!/^#[0-9a-f]{3,8}$/i.test(value)) return value;
  let hex = value.slice(1);
  if (hex.length === 3 || hex.length === 4) hex = [...hex].map((c) => c + c).join('');
  if (![6, 8].includes(hex.length)) return value;
  const rgb = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
  const min = Math.min(...rgb),
    max = Math.max(...rgb),
    delta = max - min;
  const luminance = rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722;
  const [r, g, b] = rgb;
  const role =
    r > g * 1.15 && r > b * 1.08
      ? 'danger'
      : g > r * 1.08 && g > b * 0.98
        ? 'success'
        : r > b * 1.15 && g > b * 1.08
          ? 'warning'
          : b > g * 1.15 && r > g * 1.2
            ? 'accent'
            : b > r * 1.18 && b > g * 1.08
              ? 'info'
              : 'accent';
  if (property.includes('shadow')) return hex.length === 8 ? '#00000040' : '#000000';
  if (hex.length === 8 && min > 220) return '#ffffff0f';
  const background = property.includes('background');
  const border = property.includes('border') || property.includes('outline');
  if (background) {
    if (min > 245) return 'var(--card)';
    if (luminance > 195)
      return delta > 20 && role !== 'accent' ? `var(--${role}-soft)` : 'var(--surface-soft)';
    return value;
  }
  if (border) return luminance > 155 ? 'var(--border)' : delta > 45 ? 'var(--purple)' : 'var(--border)';
  if (property === 'color' || property === 'fill' || property === 'stroke' || property === 'caret-color') {
    if (min > 235) return value; // white foreground on filled actions
    if (delta > 55 && luminance < 190) return role === 'accent' ? 'var(--purple)' : `var(--${role})`;
    return luminance < 85 ? 'var(--ink)' : 'var(--muted)';
  }
  return value;
}
const root = 'src/app';
const files = fs
  .readdirSync(root, { recursive: true })
  .filter(
    (file) =>
      file.endsWith('.css') && !['theme.css', 'dark-surfaces.css'].includes(file.replaceAll('\\', '/')),
  )
  .sort();
const output = postcss.root();
output.append(
  postcss.comment({
    text: 'Generated by scripts/generate-dark-surfaces.mjs. Semantic overrides for existing UI; document slide colors are preserved.',
  }),
);
for (const file of files) {
  const css = postcss.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  function visit(container, destination) {
    for (const node of container.nodes ?? []) {
      if (node.type === 'atrule' && ['media', 'supports', 'container'].includes(node.name)) {
        const child = postcss.atRule({ name: node.name, params: node.params });
        visit(node, child);
        if (child.nodes?.length) destination.append(child);
      }
      if (node.type !== 'rule' || !node.nodes || node.selector.includes('&')) continue;
      const selectors = postcss.list
        .comma(node.selector)
        .filter(
          (selector) =>
            !/\.presentation-slide|\.slide-(?:object|text|shape|image|chart|pie|data-chart)|\.data-chart--slide|\.presentation-theme-swatch|\.slide-preview/.test(
              selector,
            ),
        );
      if (!selectors.length) continue;
      const rule = postcss.rule({
        selector: selectors
          .map((selector) => {
            if (selector === ':root') return 'html[data-theme="dark"]';
            if (selector.startsWith('body')) return 'html[data-theme="dark"] ' + selector;
            return 'html[data-theme="dark"] ' + selector;
          })
          .join(',\n'),
      });
      for (const declaration of node.nodes) {
        if (declaration.type !== 'decl' || declaration.prop.startsWith('--')) continue;
        const mapped = declaration.value
          .replace(/#[0-9a-f]{3,8}\b/gi, (value) => darkColor(declaration.prop, value))
          .replace(/\bwhite\b/g, declaration.prop.includes('background') ? 'var(--card)' : 'white');
        if (mapped !== declaration.value)
          rule.append(
            postcss.decl({ prop: declaration.prop, value: mapped, important: declaration.important }),
          );
      }
      if (rule.nodes?.length) destination.append(rule);
    }
  }
  visit(css, output);
}
fs.writeFileSync(path.join(root, 'dark-surfaces.css'), output.toString() + '\n');
console.log(`Generated dark surface overrides from ${files.length} CSS files.`);
